# ---------- Chinese: per-character pinyin, zhuyin and Simplified ----------
# A Chinese sentence is plain Traditional text (Taiwan wording) or {"t": text, "p":
# pinyin}. Without "p" the pinyin is generated by tools/zh_reading.py (the grammar's
# house style: Taiwan readings, neutral tones, 一 / 不 sandhi) and printed for review.
# Segments are one per character: [char, pinyin, glossary, zhuyin, simplified].
ZH_REVIEW = []
_zh_tools = {}
# words zh_reading gets wrong here (覺 read jué, 長 zhǎng, 星期一 with 一 changing tone);
# added to its lexicon for this build only, so the grammar's readings don't move
READING_ZH_WORDS = {'睡覺': 'shuìjiào', '長頸鹿': 'chángjǐnglù', '星期一': 'xīngqíyī',
                    '教我': 'jiāowǒ', '台南': 'Táinán', '小明': 'Xiǎomíng', '小美': 'Xiǎoměi'}


def zh_tools():
    if not _zh_tools:
        import opencc
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import zh_reading
        from pypinyin.style.bopomofo import BopomofoConverter
        zh_reading.LEXICON.update(READING_ZH_WORDS)
        _zh_tools.update(cc=opencc.OpenCC('tw2s'), zr=zh_reading, bpmf=BopomofoConverter())
    return _zh_tools


def zh_bopomofo(syll):
    z = zh_tools()['bpmf'].to_bopomofo(syll.lower())
    return '˙' + z[:-1] if z.endswith('˙') else z      # Taiwan writes the neutral-tone dot first


def zh_syllables(text, pinyin, where, problems):
    """one pinyin syllable per Han character of text"""
    try:
        return [syl for _, _, part in zh_tools()['zr'].align(text, pinyin) for syl in part]
    except ValueError as e:
        problems.append(f'{where}: {e}')
        return None


def sentence_zh(marked, glossary, where, problems, short):
    t = zh_tools()
    text, given = (marked['t'], marked.get('p')) if isinstance(marked, dict) else (marked, None)
    pinyin = given or t['zr'].reading(text, sentence=not short)
    if not given:
        ZH_REVIEW.append(f'{where}: {text}  →  {pinyin}')
    sylls = zh_syllables(text, pinyin, where, problems) or []
    gloss = [None] * len(text)
    for gi, g in enumerate(glossary or []):
        for form in g.get('m') or [g['w']]:
            for m in re.finditer(re.escape(form), text):
                if any(gloss[i] is not None for i in range(m.start(), m.end())):
                    continue
                for i in range(m.start(), m.end()):
                    gloss[i] = gi
    segs, k = [], 0
    for i, ch in enumerate(text):
        if t['zr'].is_hanzi(ch) and k < len(sylls):
            py = sylls[k]
            k += 1
            simp = t['cc'].convert(ch)
            segs.append([ch, py, gloss[i], zh_bopomofo(py), simp if len(simp) == 1 else ch])
        elif segs and segs[-1][1] is None and segs[-1][2] == gloss[i]:
            segs[-1][0] += ch
            segs[-1][4] += ch
        else:
            segs.append([ch, None, gloss[i], None, ch])
    return segs, text, text


def zh_glossary(g, where, problems):
    """a glossary word with its Simplified form and zhuyin"""
    t = zh_tools()
    sylls = zh_syllables(g['w'], g['r'], where + ' glossary ' + g['w'], problems) or []
    return {'w': g['w'], 'r': g['r'], 'simp': ''.join(t['cc'].convert(c) for c in g['w']),
            'zy': ' '.join(zh_bopomofo(x) for x in sylls), 'zh': g.get('zh', ''), 'en': g.get('en', '')}


# ---------- Russian: stress marks ----------
# Russian is written with a stress mark (U+0301 after the vowel) on every word of two
# or more syllables; the page can hide them. Segments keep the marks, the plain text
# (recordings, glossary matching) drops them, and the kana slot holds the marked text.
ACUTE = '\u0301'
RU_VOWELS = set('аеёиоуыэюяАЕЁИОУЫЭЮЯ')


def ru_plain(text):
    return unicodedata.normalize('NFC', text.replace(ACUTE, ''))


def ru_stress_problems(text, where, problems):
    """words of 2+ syllables without a mark, marks off a vowel, two marks in a word"""
    for word in re.findall(r"[А-Яа-яЁё\u0301-]+", text):
        for part in word.split('-'):
            vowels = sum(c in RU_VOWELS for c in part)
            marks = part.count(ACUTE)
            if vowels >= 2 and not marks and not re.search('[Ёё]', part):
                problems.append(f'{where}: no stress mark on "{part}" in: {text}')
            if marks > 1:
                problems.append(f'{where}: two stress marks in "{part}"')
            for i, c in enumerate(part):
                if c == ACUTE and (i == 0 or part[i - 1] not in RU_VOWELS):
                    problems.append(f'{where}: a stress mark not after a vowel in "{part}"')


def sentence_ru(marked, glossary, where, problems):
    text = unicodedata.normalize('NFC', marked)
    ru_stress_problems(text, where, problems)
    clusters = []                       # one per letter, with its stress mark
    for ch in text:
        if ch == ACUTE and clusters:
            clusters[-1] += ch
        else:
            clusters.append(ch)
    plain = ''.join(c.replace(ACUTE, '') for c in clusters)
    gloss = [None] * len(plain)
    for gi, g in enumerate(glossary or []):
        for form in g.get('m') or [g['w']]:
            for m in re.finditer(re.escape(ru_plain(form)), plain):
                if any(gloss[i] is not None for i in range(m.start(), m.end())):
                    continue
                for i in range(m.start(), m.end()):
                    gloss[i] = gi
    segs = []
    for i, c in enumerate(clusters):
        if segs and segs[-1][2] == gloss[i]:
            segs[-1][0] += c
        else:
            segs.append([c, None, gloss[i]])
    return segs, plain, text


def ru_glossary(g, where, problems):
    """w without stress, r with it (marked like the text)"""
    r = unicodedata.normalize('NFC', g['r'])
    if ru_plain(r) != unicodedata.normalize('NFC', g['w']):
        problems.append(f'{where} glossary {g["w"]}: r "{r}" is not w with stress marks')
    ru_stress_problems(r, where + ' glossary', problems)
    return {'w': g['w'], 'r': r, 'zh': g['zh'], 'en': g['en']}


def tokens(marked):
    """'七時{しちじ}に' -> [('七時', 'しちじ'), ('に', None)]"""
    out, pos = [], 0
    for m in RUBY.finditer(marked):
        if m.start() > pos:
            out.append((marked[pos:m.start()], None))
        out.append((m.group(1), m.group(2)))
        pos = m.end()
    if pos < len(marked):
        out.append((marked[pos:], None))
    return out


def sentence(marked, glossary, where, problems, lang='ja', short=False):
    """segments, plain text and kana of one sentence; glossary=None for questions.
    Only Japanese uses {furigana}; elsewhere the kana is the plain text. Chinese
    goes to sentence_zh (short: an option or title, not a sentence)."""
    if lang == 'zh':
        return sentence_zh(marked, glossary, where, problems, short)
    if lang == 'ru':
        return sentence_ru(marked, glossary, where, problems)
    if '{' in RUBY.sub('', marked) or '}' in RUBY.sub('', marked):
        problems.append(f'{where}: a {{reading}} without kanji right before it: {marked}')
    toks = tokens(marked)
    plain = ''.join(t for t, _ in toks)
    kana = ''.join(r or t for t, r in toks)
    bare = [ch for t, r in toks if r is None for ch in t if re.match(KANJI, ch)]
    if bare and lang == 'ja':
        problems.append(f'{where}: kanji without furigana {"".join(bare)}: {marked}')
    # per character: which ruby group it belongs to (None = plain kana / punctuation)
    group, owner = [], []
    for gi, (t, r) in enumerate(toks):
        for _ in t:
            group.append(gi if r else None)
            owner.append(gi)
    gloss = [None] * len(plain)
    for gi, g in enumerate(glossary or []):
        for form in g.get('m') or [g['w']]:
            for m in re.finditer(re.escape(form), plain):
                a, b = m.start(), m.end()
                cut_start = a > 0 and group[a] is not None and group[a - 1] == group[a]
                cut_end = b < len(plain) and group[b - 1] is not None and group[b] == group[b - 1]
                if cut_start or cut_end:
                    problems.append(f'{where}: "{form}" cuts a furigana group in: {marked}')
                    continue
                if any(gloss[i] is not None for i in range(a, b)):
                    continue
                for i in range(a, b):
                    gloss[i] = gi
    # merge characters into segments: a ruby group stays whole, plain runs split where
    # the glossary underline starts or ends
    segs = []
    for i, ch in enumerate(plain):
        gi = owner[i]
        tok_text, tok_ruby = toks[gi]
        key = (gi if tok_ruby else None, gloss[i])
        if segs and segs[-1][3] == key and (tok_ruby is None or segs[-1][4] == gi):
            segs[-1][0] += ch
        else:
            segs.append([ch, tok_ruby, gloss[i], key, gi])
    return [[t, r, g] for t, r, g, _, _ in segs], plain, kana


def used(glossary):
    return {g for s in glossary for g in s}


