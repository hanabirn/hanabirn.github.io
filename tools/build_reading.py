def known_kanji(level):
    order = ['N5', 'N4', 'N3', 'N2', 'N1']
    out = set()
    for lv in order[:order.index(level) + 1] if level in order else []:
        out |= KANJI_LEVEL.get(lv, set())
    return out


def ja_segs(marked, where, problems, known):
    """a Japanese line of a round -> segments [text, furigana, None, known (1 = a kanji of the
    level or below: its furigana hidden until asked)]"""
    segs, _plain, _kana = sentence(marked, None, where, problems, 'ja', short=True)
    out = []
    for t, r, g in segs:
        kanji = [ch for ch in t if re.match(KANJI, ch)]
        out.append([t, r, g, 1 if r and kanji and all(ch in known for ch in kanji) else 0])
    return out


def plain_of(marked):
    return ''.join(t for t, _ in tokens(marked))
SET_TYPES = {'text', 'notice', 'chart', 'order', 'insert', 'headline'}


def build_sets(data, name, problems):
    out, seen = [], set()
    for st in data.get('sets', []):
        sw = f'{name}/{st.get("id")}'
        if st.get('id') in seen:
            problems.append(f'{sw}: duplicate set id')
        seen.add(st.get('id'))
        items, n = [], 0
        for k, it in enumerate(st.get('items', [])):
            iw = f'{sw} item {k + 1}'
            typ = it.get('type', 'text')
            if typ not in SET_TYPES:
                problems.append(f'{iw}: unknown type {typ}')
            need = {'text': ['text'], 'insert': ['text', 'box'], 'headline': ['text'], 'order': ['parts'],
                    'notice': ['notice'], 'chart': ['chart']}.get(typ, [])
            for key in need:
                if not it.get(key):
                    problems.append(f'{iw}: a {typ} item needs "{key}"')
            if typ == 'order' and len(it.get('parts', [])) != 4:
                problems.append(f'{iw}: an order item has 4 parts')
            if typ == 'insert' and not all(m in it.get('text', '') for m in '㉠㉡㉢㉣'):
                problems.append(f'{iw}: an insert text marks ㉠ ㉡ ㉢ ㉣')
            tr = it.get('tr') or {}
            for lang in ('zh', 'en'):
                if not tr.get(lang):
                    problems.append(f'{iw}: no {lang} translation (tr)')
            qs = []
            for qi, q in enumerate(it.get('questions', [])):
                n += 1
                qw = f'{iw} Q{qi + 1}'
                ask = q.get('ask') or it.get('ask')
                if ask not in SET_ASKS:
                    problems.append(f'{qw}: ask "{ask}" is not one of {sorted(SET_ASKS)}')
                opts = q.get('options', [])
                if len(opts) != 4 or not 0 <= q.get('answer', -1) < 4:
                    problems.append(f'{qw}: needs 4 options and an answer 0-3')
                if len(set(opts)) != len(opts):
                    problems.append(f'{qw}: two options are the same')
                for lang in ('zh', 'en'):
                    if not q.get(lang):
                        problems.append(f'{qw}: no {lang} explanation')
                qs.append({'ask': ask, 'q': q.get('q', ''), 'options': opts, 'answer': q.get('answer'),
                           'zh': q.get('zh', ''), 'en': q.get('en', '')})
            if not qs:
                problems.append(f'{iw}: no questions')
            item = {'type': typ, 'tr': {'zh': tr.get('zh', ''), 'en': tr.get('en', '')}, 'questions': qs}
            for key in ('text', 'box', 'parts', 'notice', 'chart', 'title', 'mondai'):
                if key in it:
                    item[key] = it[key]
            if data.get('lang') == 'ja':
                # segments for the page (furigana), and the plain text where the source had {readings}
                known = known_kanji(data.get('level', ''))
                seg = lambda s, w: ja_segs(s, w, problems, known)
                if 'text' in it:
                    item['text_t'] = [seg(line, iw) for line in it['text'].split('\n')]
                    item['text'] = plain_of(it['text'])
                if 'notice' in it:
                    nt = it['notice']   # (not n: that counts the questions)
                    item['notice_t'] = {'title': seg(nt.get('title', ''), iw), 'rows': [[seg(a, iw), seg(b, iw)] for a, b in nt.get('rows', [])],
                                        'lines': [seg(l, iw) for l in nt.get('lines', [])], 'foot': seg(nt.get('foot', ''), iw)}
                    item['notice'] = {'title': plain_of(nt.get('title', '')), 'rows': [[plain_of(a), plain_of(b)] for a, b in nt.get('rows', [])],
                                      'lines': [plain_of(l) for l in nt.get('lines', [])], 'foot': plain_of(nt.get('foot', ''))}
                for q in qs:
                    if q['q']:
                        q['q_t'] = seg(q['q'], iw)
                        q['q'] = plain_of(q['q'])
                    q['options_t'] = [seg(o, iw) for o in q['options']]
                    q['options'] = [plain_of(o) for o in q['options']]
                if not it.get('mondai'):
                    problems.append(f'{iw}: a Japanese round item needs "mondai" (4, 5, 6 …)')
            if it.get('words'):
                item['words'] = [{'w': w['w'], 'zh': w.get('zh', ''), 'en': w.get('en', '')} for w in it['words']]
            items.append(item)
        if st.get('mock') and not st.get('minutes'):
            problems.append(f'{sw}: a mock exam needs "minutes"')
        out.append({'id': st['id'], 'mock': bool(st.get('mock')), 'minutes': st.get('minutes', 0),
                    'start': st.get('start', 1), 'count': n, 'items': items})
        if not st.get('mock') and n == 0:
            problems.append(f'{sw}: no questions')
    return out


def build(src, problems):
    data = json.loads(src.read_text(encoding='utf-8'))
    name = src.stem
    for key in ('id', 'lang', 'level', 'order'):
        if key not in data:
            problems.append(f'{name}: missing "{key}"')
    if 'passages' not in data and 'sets' not in data:
        problems.append(f'{name}: no "passages" or "sets"')
    out = {k: data[k] for k in ('id', 'lang', 'level', 'order')}
    out['passages'] = []
    out['sets'] = build_sets(data, name, problems)
    seen = set()
    for p in data.get('passages', []):
        where = f'{name}/{p.get("id")}'
        if p['id'] in seen:
            problems.append(f'{where}: duplicate id')
        seen.add(p['id'])
        gl = p.get('glossary', [])
        title, _, title_kana = sentence(p['title']['text'], None, where + ' title', problems, data['lang'], short=True)
        paras, hits, length = [], set(), 0
        for k, para in enumerate(p['paragraphs']):
            sents = []
            for s in para['s']:
                segs, plain, kana = sentence(s, gl, f'{where} ¶{k + 1}', problems, data['lang'])
                hits |= {sg[2] for sg in segs if sg[2] is not None}
                if data['lang'] in CHAR_LANGS:
                    length += len(re.sub(r'[\s、。「」！？・，．]', '', plain))
                else:
                    length += len(WORD.findall(plain))
                sents.append({'t': segs, 'plain': plain, 'kana': kana})
            # Chinese passages are translated into English only and English ones into
            # Chinese only (the other would repeat them)
            for lang in {'zh': ('en',), 'en': ('zh',)}.get(data['lang'], ('zh', 'en')):
                if not para.get(lang):
                    problems.append(f'{where} ¶{k + 1}: no {lang} translation')
            paras.append({'s': sents, 'zh': para.get('zh', ''), 'en': para.get('en', '')})
        for gi, g in enumerate(gl):
            if gi not in hits:
                problems.append(f'{where}: glossary word {g["w"]} never appears (set "m")')
        mcq = p.get('mcq', [])
        tf = p.get('tf', [])
        if len(mcq) != MCQ_COUNT or len(tf) != TF_COUNT:
            problems.append(f'{where}: {len(mcq)} multiple-choice and {len(tf)} true/false (want {MCQ_COUNT} + {TF_COUNT})')
        out_mcq = []
        for qi, q in enumerate(mcq):
            qw = f'{where} Q{qi + 1}'
            if len(q.get('options', [])) != 4 or not 0 <= q.get('answer', -1) < 4:
                problems.append(f'{qw}: needs 4 options and an answer 0-3')
            if len(set(q['options'])) != len(q['options']):
                problems.append(f'{qw}: two options are the same')
            for lang in ('zh', 'en'):
                if not q.get(lang):
                    problems.append(f'{qw}: no {lang} explanation')
            out_mcq.append({'q': sentence(q['q'], None, qw, problems, data['lang'])[0],
                            'options': [sentence(o, None, qw, problems, data['lang'], short=True)[0] for o in q['options']],
                            'answer': q['answer'], 'zh': q.get('zh', ''), 'en': q.get('en', '')})
        out_tf = []
        for ti, t in enumerate(tf):
            tw = f'{where} TF{ti + 1}'
            if not isinstance(t.get('answer'), bool):
                problems.append(f'{tw}: answer must be true or false')
            for lang in ('zh', 'en'):
                if not t.get(lang):
                    problems.append(f'{tw}: no {lang} explanation')
            out_tf.append({'s': sentence(t['s'], None, tw, problems, data['lang'])[0], 'answer': t['answer'],
                           'zh': t.get('zh', ''), 'en': t.get('en', '')})
        if sum(t['answer'] for t in tf) in (0, len(tf)) and tf:
            problems.append(f'{where}: the true/false answers are all the same')
        out['passages'].append({
            'id': p['id'], 'topic': p.get('topic', ''),
            'title': {'t': title, 'kana': title_kana, 'zh': p['title'].get('zh', ''), 'en': p['title'].get('en', '')},
            'length': length, 'paragraphs': paras,
            'glossary': [zh_glossary(g, where, problems) if data['lang'] == 'zh'
                         else ru_glossary(g, where, problems) if data['lang'] == 'ru'
                         else {k: g[k] for k in ('w', 'r', 'zh', 'en')} for g in gl],
            'mcq': out_mcq, 'tf': out_tf})
    return out


def level_words(lang, level):
    words = set()
    for prefix in LEVEL_SETS.get((lang, level), []):
        for f in (ROOT / 'data' / 'vocab').glob(prefix + '*.json'):
            for row in json.loads(f.read_text(encoding='utf-8'))['words']:
                words.add(row[0])
                if len(row) > 1 and row[1]:
                    words.add(row[1])
    return words


def main():
    import opencc
    cc = opencc.OpenCC('tw2sp')
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from build_grammar import add_hans
    from content_i18n import fill, report_missing
    problems, index = [], []
    OUT.mkdir(parents=True, exist_ok=True)
    for src in sorted(SRC.glob('*.json')):
        data = build(src, problems)
        if not data['passages'] and not data['sets']:
            continue
        known = level_words(data['lang'], data['level'])
        if known:
            for p in data['passages']:
                # 勉強する / 공부하다 / se lever: the lists have 勉強 / 공부 / lever
                stem = lambda w: w[:-2] if w.endswith(('する', '하다')) else re.sub(r"^(se |s')", '', w)
                outside = [g['w'] for g in p['glossary'] if stem(g['w']) not in known and stem(g['r']) not in known]
                if outside:
                    print(f'  {data["id"]}/{p["id"]}: glossary words outside the level lists: {", ".join(outside)}')
        add_hans(data, cc)
        report_missing(fill(data), data['id'])   # ja ko ru fr es de (tools/content_i18n.py)
        (OUT / f'{data["id"]}.json').write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
        index.append({'id': data['id'], 'lang': data['lang'], 'level': data['level'], 'order': data['order'],
                      'count': len(data['passages']) + len(data['sets'])})
        print(f'{data["id"]}: {len(data["passages"])} passages, lengths {[p["length"] for p in data["passages"]]}'
              + (f', sets {[(st["id"], st["count"]) for st in data["sets"]]}' if data['sets'] else ''))
    if ZH_REVIEW:
        print('\nChinese pinyin to review (generated):')
        for line in ZH_REVIEW:
            print('  ' + line)
    index.sort(key=lambda l: (LANG_ORDER.index(l['lang']) if l['lang'] in LANG_ORDER else 99, l['order']))
    (OUT / 'index.json').write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding='utf-8')
    if problems:
        print('\nPROBLEMS:')
        for p in problems:
            print('  ' + p)
        sys.exit(1)


if __name__ == '__main__':
    main()
