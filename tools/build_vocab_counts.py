"""Writes js/vocab-counts.js: the word count of every graded list in data/vocab (not the topic sets), so the
單字 page's 檢定等級 tab can show "294 字 · 0/30 關" before a list has been loaded on the device (2026-11-13).
Re-run after build_vocab.py:  python tools/build_vocab_counts.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
counts = {}
for p in sorted((ROOT / 'data' / 'vocab').glob('*.json')):
    if p.stem.startswith('tp_') or p.stem == 'clash':
        continue
    d = json.loads(p.read_text(encoding='utf-8'))
    counts[p.stem] = len(d['words'])
body = ', '.join(f"'{k}': {v}" for k, v in counts.items())
(ROOT / 'js' / 'vocab-counts.js').write_text(
    '// Generated by tools/build_vocab_counts.py — word counts of the graded lists in data/vocab; do not edit.\n'
    f'const VOCAB_COUNTS = {{ {body} }};\n', encoding='utf-8')
print(len(counts), 'lists')
